def main():
    start = dt.date(2026, 10, 10)
    db = {}
    seen = set()
    for i, (id_, cat, unit, title, summary) in enumerate(RAW):
        if id_ in seen:
            raise SystemExit('重複 id ' + id_)
        seen.add(id_)
        if cat not in CATS:
            raise SystemExit('未知欄目 ' + cat)
        title = title if title.startswith('【範例】') else '【範例】' + title
        if not summary.startswith('【範例稿】'):
            raise SystemExit('摘要未標示 ' + id_)
        if any(ch in title + summary for ch in '「」『』"'):
            raise SystemExit('含引號，可能像真實引述 ' + id_)
        n = len(summary)
        if not 50 <= n <= 200:
            raise SystemExit(f'字數 {n} {id_}\n{summary}')
        db[id_] = {
            'id': id_,
            'title': title,
            'date': (start - dt.timedelta(days=i)).isoformat(),
            'category': cat,
            'unit': unit,
            'summary': summary,
            'sample': True,
            'summary_ok': True,
            'added': '2026-10-10',
        }
    json.dump(db, open('news_db.json', 'w'), ensure_ascii=False, indent=2)
    json.dump([], open('pending_summary.json', 'w'), ensure_ascii=False, indent=2)
    print('範例稿', len(db), '則')

if __name__ == '__main__':
    main()
